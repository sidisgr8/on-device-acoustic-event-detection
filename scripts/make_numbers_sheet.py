"""Write docs/study/RESULTS_NUMBERS.md: a plain facts sheet of the final numbers, no prose.

    .venv-post/bin/python scripts/make_numbers_sheet.py

Everything is read from results/tables/*.csv (run scripts/make_tables.py first) and results/latency/latency.json;
nothing is typed in by hand. Each block names its source file and says how many folds it covers.
"""
import json
from pathlib import Path

import pandas as pd

T = Path("results/tables")
OUT = Path("docs/study/RESULTS_NUMBERS.md")


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(r[c]) else str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def read(name):
    p = T / f"{name}.csv"
    return pd.read_csv(p, dtype=str, keep_default_na=False) if p.exists() else None


def block(title, source, folds, df, note=None):
    out = [f"## {title}", "", f"Source: `{source}`. Folds: {folds}.", ""]
    out.append(md(df) if df is not None and len(df) else "(no data)")
    if note:
        out += ["", note]
    return "\n".join(out) + "\n"


def quant_with_latency():
    q = read("quantization")
    p = Path("results/latency/latency.json")
    if q is None or not p.exists():
        return q
    lat = {}
    for r in json.loads(p.read_text())["forward"]:
        if "median_ms" in r:
            lat[(r["experiment"], r["variant"], r["threads"])] = r
    names = {  # table model name -> experiment id
        "CNN baseline": "cnn_baseline", "MobileNetV3-S (scratch)": "mobilenetv3_small_scratch",
        "MobileNetV3-S (ImageNet)": "mobilenetv3_small_imagenet", "CRNN (CNN+BiGRU)": "crnn", "AST": "ast"}
    for th in (1, 4):
        q[f"Latency {th}T median (ms)"] = [
            f"{lat[(names[m], v, th)]['median_ms']:.2f}" if (names[m], v, th) in lat else "-"
            for m, v in zip(q["Model"], q["Variant"])]
    return q.drop(columns=["Note"], errors="ignore")


def diagnostics():
    """Validation-only diagnostics (D-44, D-45): ImageNet MobileNetV3-S int8 remedies and pruning recovery."""
    import numpy as np
    D = Path("results/diagnostics")
    out = []
    p = D / "mnv3_quant_val.json"
    if p.exists():
        res = json.loads(p.read_text())["models"]
        rows = []
        for exp, name in (("mobilenetv3_small_imagenet", "ImageNet"), ("mobilenetv3_small_scratch", "scratch")):
            f = res[exp]
            folds = list(f)
            fp = np.mean([f[k]["fp32"]["val_acc"] for k in folds])
            rows.append([name, "fp32 (reference)", f"{100 * fp:.1f}"])
            for grp in ("candidates", "onnx"):
                for n in f[folds[0]][grp]:
                    v = [f[k][grp][n].get("val_acc", np.nan) for k in folds]
                    rows.append([name, n, f"{100 * np.nanmean(v):.1f}"])
        out.append(pd.DataFrame(rows, columns=["Model", "Int8 variant", "Validation acc, mean of 3 folds (%)"]))
    p = D / "prune_recovery_val.json"
    rec = None
    if p.exists():
        runs = json.loads(p.read_text())["runs"]
        agg = {}
        for r in runs:
            agg.setdefault((r["sparsity"], r["lr"], r["epochs"], bool(r.get("main_run_reference"))), []).append(r["val_acc_best"])
        rec = pd.DataFrame([[f"{int(sp * 100)}%", f"{lr:g}", ep, "main run" if ref else "diagnostic", len(v), f"{100 * np.mean(v):.1f}"]
                            for (sp, lr, ep, ref), v in sorted(agg.items())],
                           columns=["Sparsity", "Fine-tune lr", "Epochs", "Row", "Folds", "Validation acc mean (%)"])
    return (out[0] if out else None), rec


def main():
    parts = ["# Final numbers (facts sheet, generated by scripts/make_numbers_sheet.py; no prose)", "",
             "Generated from the result files; do not edit by hand. Accuracy and macro-F1 are test-fold means ± sample std over folds. "
             "Protocol v2, seed 42, one run per fold. Quantization: all 10 folds. Pruning: folds 1, 5, 9 only (AST: 30 % and 70 %). "
             "Latency: fold-1 weights, 3 repeats (D-40).", ""]
    parts.append(block("Master comparison (main rows, plus the labelled ablation row)", "results/tables/master_comparison.csv",
                       "10 of 10 for every row", read("master_comparison"),
                       "Latency columns are the fp32 PyTorch forward pass, batch 1, median over 3 repeats."))
    parts.append(block("Per-class F1 (mean ± std over folds)", "results/tables/per_class_f1.csv", "10 of 10", read("per_class_f1")))
    parts.append(block("Accuracy on padded vs full-length test clips (pooled over folds)", "results/tables/padded_vs_full.csv",
                       "10 of 10", read("padded_vs_full")))
    parts.append(block("Top confusions (summed over folds)", "results/tables/top_confusions.csv", "10 of 10", read("top_confusions")))
    parts.append(block("Paired per-fold comparison, accuracy (A - B)", "results/tables/paired_accuracy.csv", "10 of 10", read("paired_accuracy"),
                       "Holm adjustment is over the 10 pairs of this table; 10 folds, one seed, overlapping training sets: intervals are optimistic."))
    parts.append(block("Paired per-fold comparison, macro-F1 (A - B)", "results/tables/paired_macro_f1.csv", "10 of 10", read("paired_macro_f1")))
    parts.append(block("Ablation A-1 (MobileNetV3-S scratch at lr 3e-4) vs the main MobileNetV3-S runs", "results/tables/ablation_a1.csv",
                       "10 of 10", read("ablation_a1")))
    parts.append(block("Post-training 8-bit quantization (accuracy, size, latency per variant)",
                       "results/tables/quantization.csv + results/latency/latency.json", "accuracy and size: 10 of 10; latency: fold 1 weights",
                       quant_with_latency(),
                       "Delta is relative to the fp32 PyTorch model on the same fold (mean ± std over folds of the per-fold difference)."))
    parts.append(block("Global magnitude pruning + 3 epochs fine-tuning", "results/tables/pruning.csv", "3 of 10 (folds 1, 5, 9) - NOT comparable with the 10-fold rows above",
                       read("pruning"),
                       "Non-zero parameters count all parameters (biases and normalisation included); sparsity targets apply to the prunable weights. "
                       "Delta is relative to the unpruned model on the same three folds. Rows labelled \"extended fine-tune recipe (lr and epochs chosen on validation data of the ImageNet MobileNetV3-S only)\" "
                       "are additional (lr 3e-4, 10 epochs, 50 % and 70 %, D-47); the unlabelled rows are the main run (lr 3e-5, 3 epochs) and the 0 % control, and are unchanged."))
    lat = read("latency")
    parts.append(block("CPU latency, every variant", "results/tables/latency.csv (from results/latency/latency.json)",
                       "fold 1 weights only; 3 repeats", lat,
                       "Batch 1, one 4 s clip, 20 warm-up + 200 timed runs, median and p95, 1 and 4 threads; median over 3 repeats of the repeat medians."))
    q, rec = diagnostics()
    parts.append(block("Diagnostic: ImageNet vs scratch MobileNetV3-S int8 remedies (VALIDATION data, not test; D-44)", "results/diagnostics/mnv3_quant_val.json",
                       "folds 1, 5, 9 (validation folds 2, 6, 10)", q, "No remedy restored fp32 accuracy; no new variant was promoted to a test result."))
    parts.append(block("Diagnostic: ImageNet MobileNetV3-S pruning recovery (VALIDATION data, not test; D-45)", "results/diagnostics/prune_recovery_val.json",
                       "folds 1, 5, 9", rec, "Diagnostic only; the main pruning rows are unchanged. Unpruned validation accuracy 75.3/78.9/86.4 (mean 80.2)."))
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
