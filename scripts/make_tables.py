"""Write the comparison tables (CSV + Markdown) and figures from result files (protocol v2 only).

    python scripts/make_tables.py [--results results] [--out results/tables] [--figures results/figures]

Refuses to mix protocol versions or configs. Nothing is hand-edited: rerun after new results arrive.
"""
import argparse
import json
from pathlib import Path

from src.analysis import aggregate as A
from src.analysis.errors import analysis, top_confusions_table
from src.analysis.figures import make_all
from src.analysis.paired import ABLATION_NOTES, PAIRED_NOTES, ablation_table, paired_table


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--ckpt-dir", default="checkpoints")
    ap.add_argument("--out", default="results/tables")
    ap.add_argument("--figures", default="results/figures")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    std = "± is the sample standard deviation over the folds shown in the 'Folds' column (test folds)."
    tables = [
        ("master_comparison", "Model comparison (protocol v2, test folds)", A.master_table(a.results, a.ckpt_dir),
         [std, "MACs per 4 s clip are counted from the model code (scripts/compute_complexity.py: Conv/Linear/GRU, plus attention for AST); parameters, size, MACs and latency are four different costs and do not rank models identically.",
          "Rows marked [Ablation A-1] are the pre-declared pretraining-control ablation (D-38); they are not part of the main comparison, figures or paired table.",
          "Latency columns stay '-' until scripts/benchmark_latency.py has been run on an idle machine."]),
        ("per_class_f1", "Per-class F1 (mean ± std over folds)", A.per_class_f1_table(a.results), [std]),
        ("padded_vs_full", "Accuracy on padded vs full-length test clips (pooled over folds)",
         A.padded_vs_full_table(a.results), ["Padded clips are those shorter than 4 s in the original recording (zero-padded)."]),
        ("top_confusions", "Most frequent confusions per model (summed over folds)", top_confusions_table(a.results),
         ["Rows are the five largest off-diagonal cells of the summed confusion matrix; see results/figures/confusion_*.png."]),
        ("paired_accuracy", "Paired per-fold comparison: test accuracy (all model pairs)",
         paired_table(a.results, metric="accuracy"), PAIRED_NOTES),
        ("paired_macro_f1", "Paired per-fold comparison: macro-F1 (all model pairs)",
         paired_table(a.results, metric="macro_f1"), PAIRED_NOTES[:1] + PAIRED_NOTES[1:]),
        ("ablation_a1", "Ablation A-1 vs the main MobileNetV3-S runs: paired per-fold accuracy",
         ablation_table(a.results, "accuracy"), ABLATION_NOTES),
        ("quantization", "Post-training 8-bit quantization (no retraining, test folds)", A.quant_table(a.results),
         [std, "Size is the saved file; latency is reported separately in the latency table (D-09)."]),
        ("pruning", "Global magnitude pruning + 3 epochs fine-tuning (folds 1, 5, 9)", A.prune_table(a.results),
         [std, "Unstructured sparsity does not reduce CPU latency by itself; only non-zero parameters and gzip size shrink."]),
        ("latency", "CPU latency, batch 1, one 4 s clip", A.latency_table(a.results),
         ["Measured on one machine with 1 and 4 threads; each number is the median over 3 repeats (different model order each time) of the repeat's median / p95; 'Spread' = (max-min)/median of the repeat medians, flagged above 10 %. Fold 1's weights only (latency does not depend on the weights); one pruned variant (70 %) per model. 4 threads on a 4P+6E chip are not 4 identical cores. See results/latency/latency.json for machine metadata and caveats."]),
    ]
    md = ["# Result tables (generated by scripts/make_tables.py, do not edit)\n"]
    for stem, title, df, notes in tables:
        if df is None or df.empty:
            md.append(f"### {title}\n\n*(no results yet)*\n")
            continue
        df.drop(columns=[c for c in df.columns if c.startswith("_")]).to_csv(out / f"{stem}.csv", index=False)
        md.append(A.to_markdown(df, title, notes))
    (out / "tables.md").write_text("\n".join(md))
    written = make_all(a.results, a.figures)
    print(f"tables -> {out}  ({len(tables)} tables), figures -> {a.figures} ({len(written)} files)")


if __name__ == "__main__":
    main()
